import AppKit
import Foundation

/// Copies secrets to the pasteboard marked so clipboard managers and history
/// tools skip them (nspasteboard.org conventions), and clears them after a
/// timeout unless something else has been copied since.
public final class SecureClipboard: @unchecked Sendable {
    /// "Do not record or display": honoured by Maccy, Alfred, Raycast, Paste,
    /// 1Password, Keyboard Maestro and others.
    public static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    /// "Will be removed shortly; do not save to history".
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Within the required 20–30 s window.
    public static let defaultClearAfter: TimeInterval = 25

    public static let shared = SecureClipboard(pasteboard: .general)
    private static let timerQueue = DispatchQueue(label: "strongroom.clipboard-clear")

    private let pasteboard: NSPasteboard
    private let lock = NSLock()
    private var pendingChangeCount: Int?
    private var generation = 0

    public init(pasteboard: NSPasteboard) {
        self.pasteboard = pasteboard
    }

    /// Copies `value` and schedules a clear after `clearAfter` seconds.
    @discardableResult
    public func copy(_ value: String, clearAfter: TimeInterval = SecureClipboard.defaultClearAfter) -> Int {
        pasteboard.clearContents()
        pasteboard.declareTypes([.string, Self.concealedType, Self.transientType, Self.autoGeneratedType], owner: nil)
        pasteboard.setString(value, forType: .string)
        pasteboard.setData(Data(), forType: Self.concealedType)
        pasteboard.setData(Data(), forType: Self.transientType)
        pasteboard.setData(Data(), forType: Self.autoGeneratedType)
        let count = pasteboard.changeCount

        lock.lock()
        generation += 1
        let myGeneration = generation
        pendingChangeCount = count
        lock.unlock()

        Self.timerQueue.asyncAfter(deadline: .now() + clearAfter) { [weak self] in
            self?.clearIfUnchanged(generation: myGeneration)
        }
        return count
    }

    /// Clears only if the pasteboard still holds what we put there.
    func clearIfUnchanged(generation g: Int) {
        lock.lock()
        let expected = (g == generation) ? pendingChangeCount : nil
        if g == generation { pendingChangeCount = nil }
        lock.unlock()
        guard let expected, pasteboard.changeCount == expected else { return }
        pasteboard.clearContents()
    }

    /// Clears now if we still own the contents (on lock / quit).
    public func clearNow() {
        lock.lock()
        let expected = pendingChangeCount
        pendingChangeCount = nil
        generation += 1
        lock.unlock()
        if let expected, pasteboard.changeCount == expected {
            pasteboard.clearContents()
        }
    }
}
